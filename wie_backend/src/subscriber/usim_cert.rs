//! The `MIN` a Com2uS SKT title's `usimcert.c2s` was written under.
//!
//! On its first run the title (0083660661 among them) reads
//! `MC_knlGetSystemProperty("MIN")`, encrypts it into an eighteen-byte field
//! keyed by that same `MIN` and writes the result as `usimcert.c2s`
//! (`0x114eb0`). Every run after, `0x114f34` decrypts the file with whatever
//! `MIN` the handset reports and compares the plaintext with it; another
//! handset's `MIN` reads back as noise, and the title stops at "인증 오류 입니다
//! … 오류번호 : 1004".
//!
//! A dump that carries the file therefore names the `MIN` it was made under,
//! and that is the one to report. An SKT handset's `MIN` is the subscriber
//! number without its leading zero (`1045507801`, where the number the `.mod`
//! names is `01045507801`), which is why the number alone does not pass.
//!
//! The file is `[18 bytes][sum][offset]`: byte `i` of the field is
//! `plain[i] ^ (TABLE[(offset + i) & 0xff] + min[(offset + i) % len])`, the
//! plaintext the `MIN` and zeroes after it, `sum` the low byte of the sum of
//! the eighteen encrypted bytes (`0x1151b8`).

