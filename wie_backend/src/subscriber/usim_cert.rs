/// The encrypted field's length; the sum and the offset follow it.
const FIELD: usize = 18;

/// Whether `cert` reads back as `min` under `min`, as the title checks it.
pub fn names(cert: &[u8], min: &str) -> bool {
    let (Some(field), Some(&offset)) = (cert.get(..FIELD), cert.get(FIELD + 1)) else {
        return false;
    };
    let key = min.as_bytes();
    if key.is_empty() || key.len() >= FIELD {
        return false;
    }

    let plain: Vec<u8> = field
        .iter()
        .enumerate()
        .map(|(i, &byte)| {
            let at = offset as usize + i;
            byte ^ TABLE[at & 0xff].wrapping_add(key[at % key.len()])
        })
        .collect();
    let end = plain.iter().position(|&x| x == 0).unwrap_or(plain.len());

    &plain[..end] == key
}

/// The `MIN` `cert` was written under, from among the ones `number` could be
/// reported as: the number itself, or without its leading zero.
pub fn recover_min(cert: &[u8], number: &str) -> Option<String> {
    [Some(number), number.strip_prefix('0')]
        .into_iter()
        .flatten()
        .find(|min| names(cert, min))
        .map(String::from)
}

#[cfg(test)]
mod tests {
    use super::{names, recover_min};

    /// 0083660661's `usimcert.c2s`, written under `1045507801`.
    const CERT: [u8; 20] = [
        0xca, 0x1f, 0x78, 0xdf, 0x80, 0x27, 0xb0, 0x05, 0xae, 0xbd, 0x99, 0x8d, 0x3a, 0xde, 0x65, 0xf9, 0xcb, 0x33, 0xa1, 0x00,
    ];

    #[test]
    fn the_file_names_the_min_it_was_written_under() {
        assert!(names(&CERT, "1045507801"));
        assert!(!names(&CERT, "01045507801"));
        assert!(!names(&CERT, "1089483847"));
    }

    #[test]
    fn the_min_is_the_number_without_its_leading_zero() {
        assert_eq!(recover_min(&CERT, "01045507801").as_deref(), Some("1045507801"));
        assert_eq!(recover_min(&CERT, "1045507801").as_deref(), Some("1045507801"));
        assert_eq!(recover_min(&CERT, "01089483847"), None);
        assert_eq!(recover_min(&CERT[..10], "01045507801"), None);
    }
}
